import {test,expect} from '@playwright/test'

test('shared paths restore the selected tool and workflow, not just the random seed',async({page,context})=>{
    const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
    await context.grantPermissions(['clipboard-read','clipboard-write'])
    await page.goto('/')
    await page.locator('.wayseeker-shuffle').click()
    await page.locator('.wayseeker-step-controls button').last().click()
    const name=await page.locator('.atlas-scene-topline h2').textContent()
    await page.getByRole('button',{name:'Copy this path',exact:true}).click()
    const href=await page.evaluate(()=>navigator.clipboard.readText())
    expect(new URL(href).searchParams.get('tool')).toBeTruthy()
    await page.goto(href)
    await expect(page.locator('.atlas-scene-topline h2')).toHaveText(name!)
    expect(errors).toEqual([])
})

test('the back face removes the hidden preview from keyboard navigation and search closes to its opener',async({page})=>{
    await page.goto('/')
    await page.locator('.atlas-flip').click()
    await expect(page.locator('.atlas-focus-front')).toHaveAttribute('inert','')
    await expect(page.locator('.atlas-focus-back')).not.toHaveAttribute('inert','')
    await page.getByRole('button',{name:'Index',exact:true}).click()
    await expect(page.getByRole('searchbox')).toBeFocused()
    await page.getByRole('searchbox').fill('no-such-tool-000')
    await expect(page.locator('.wayseeker-search-results')).toContainText('Try')
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button',{name:'Index',exact:true})).toBeFocused()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
})

test('Chinese and English cover explorer, notes, tool details and the return journey',async({page})=>{
    await page.goto('/')
    await page.getByRole('button',{name:'Switch to Chinese',exact:true}).click()
    await expect(page.locator('html')).toHaveAttribute('lang','zh')
    await expect(page.locator('#wayseeker-title')).toContainText('什么')
    await page.locator('.atlas-flip').click()
    await expect(page.locator('.atlas-focus-back')).toContainText('注意')
    await page.locator('.atlas-detail').click()
    await expect(page.locator('main')).toBeVisible()
    await expect(page.locator('html')).toHaveAttribute('lang','zh')
    await page.getByRole('button',{name:'切换到英文',exact:true}).click()
    await expect(page.locator('html')).toHaveAttribute('lang','en')
    await page.goBack()
    await expect(page.locator('.atlas-scene')).toBeVisible()
})
